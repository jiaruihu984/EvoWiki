"""DBOS wiring of the Bot (B3 spec §1, §3): a UTC-minute tick, the per-user `bot` queue
(partition concurrency 1), and the check / daily / dispatch workflows around the plain pipeline
functions. B1b owns the single DBOS launch; the service calls `register` right after it.

Every step catches its own exceptions and returns JSON only (`{"error": "internal", ...}` on
failure); the workflow body re-raises so DBOS marks the workflow ERROR. Time and ids come from
steps (`runtime.clock()` / `runtime.new_id`), never from the workflow body.

Workflow ids: every Bot workflow enqueued here starts with `bot:`, but the tick's own id is
generated by DBOS (`sched-bot:tick-<iso>`), so code listing Bot workflows must not rely on the
`bot:` prefix alone."""

import logging
import threading
from collections.abc import Callable
from dataclasses import asdict, dataclass
from datetime import UTC, date, datetime, timedelta
from typing import Any

from dbos import DBOS, SetEnqueueOptions, SetWorkflowID
from psycopg_pool import ConnectionPool

from evowiki.agent import lifecycle
from evowiki.bot import pipeline, runs
from evowiki.bot.gate import allow_check
from evowiki.bot.schedule import Slot, daily_slots, slot_decision
from evowiki.bot.settings import bot_serves
from evowiki.clock import Clock
from evowiki.store import bot as store_bot
from evowiki.store.db import fetch_one

log = logging.getLogger(__name__)

QUEUE = "bot"
SCHEDULE_NAME = "bot:tick"
SWEEP_EVERY_MINUTES = 10
FLOOD_WINDOW = timedelta(seconds=60)
# A tick runs the minute it is scheduled. The schedule is created with automatic_backfill=False, so
# a tick scheduled long ago is a leftover of a dead process (or of a long outage) picked up late:
# running it would redo that old minute's sweep against today's data. Five minutes is well above
# queue latency and clock skew between processes, and well below the 10-minute sweep period.
TICK_MAX_AGE = timedelta(minutes=5)


@dataclass
class BotRuntime:
    pool: ConnectionPool
    clock: Clock
    new_id: Callable[[str], str]
    # B5c: runs the user's RSI cycle for a strategy_negative trigger (pipeline.RsiRunner,
    # service.rsi_runs.bot_rsi_runner); None: such triggers fail closed
    rsi: Any = None
    # B5b: the action ledger (svc.actions); the weekly review re-orders a path through it. None:
    # cards only, no path edit
    actions: Any = None
    # the write queue (wikiapp.write_queue): the tick starts the idle page writing it may have missed
    write_queue: Any = None
    # user id -> the metered gateway (bot.card_stale's one call); None: no model, the trigger is skipped
    gateway: Any = None


_runtime: BotRuntime | None = None
_queue: Any = None
_scheduled = False                # this process applied the tick schedule (`register`)


def _rt() -> BotRuntime:
    if _runtime is None:
        raise RuntimeError("the Bot is not registered (durable.register was not called)")
    return _runtime


def _bot_off(name: str) -> bool:
    """True (with one warning) when this process has no Bot runtime. Why this can happen: DBOS
    runs every ACTIVE schedule of the application name stored in the shared system database in
    EVERY launched process (the `bot:tick` schedule created by another process fires here too, as
    `sched-bot:tick-<iso>` on DBOS's internal queue), and every process also dequeues the stored
    `bot` queue; the workflow functions are registered by importing this module. A Bot-off
    process (EVOWIKI_BOT=off, `install` never called) must neither run nor fail those: the
    workflow ends cleanly, touching no user data. Its id is then finished (a deterministic id,
    e.g. a daily slot, is not re-run by the Bot process: the next sweep covers the rest)."""
    if _runtime is not None:
        return False
    log.warning("bot workflow %s (%s) skipped: Bot off in this process", DBOS.workflow_id, name)
    return True


def install(runtime: BotRuntime) -> None:
    """Set the runtime the steps use. Call BEFORE the DBOS launch: launch recovers pending
    workflows, and a recovered `bot_tick` reaches `_rt()` at once."""
    global _runtime
    _runtime = runtime


def register(runtime: BotRuntime | None = None, *, schedule: bool = True) -> None:
    """Call right after the one DBOS launch (queues and schedules need a live DBOS); the runtime
    is `install`ed before the launch (passing it here installs it too). Fails closed: when any
    part raises, what was installed is undone (`uninstall`) and the error is re-raised."""
    global _queue, _scheduled
    try:
        if runtime is not None:
            install(runtime)
        _queue = DBOS.register_queue(QUEUE, partition_concurrency=1)
        if schedule:
            # apply_schedules creates or replaces by name: a restart never duplicates the tick.
            DBOS.apply_schedules([{
                "schedule_name": SCHEDULE_NAME, "workflow_fn": bot_tick, "schedule": "* * * * *",
                "context": None, "automatic_backfill": False}])
            _scheduled = True
    except BaseException:
        uninstall()
        raise


def uninstall() -> None:
    """Undo `install` + `register` (a failed start): the tick schedule this process applied is
    deleted (while DBOS is still up; the next start applies it again), the queue handle and the
    runtime are dropped, so nothing reaches a half-started Bot. The queue's stored config is left
    (deleting a DBOS queue loses its pending workflows). Never raises."""
    global _runtime, _queue, _scheduled
    if _scheduled:
        try:
            DBOS.delete_schedule(SCHEDULE_NAME)
        except Exception:
            log.warning("deleting the bot tick schedule after a failed start failed",
                        exc_info=True)
    _runtime, _queue, _scheduled = None, None, False


def rsi_id(trigger_id: str, attempt: int | str) -> str:
    """One RSI run per dispatch of the trigger: a `busy` run sends it back to `new`, and the next
    dispatch is the next attempt (a fresh workflow id)."""
    return f"bot:rsi:{trigger_id}:{attempt}"


def enqueue(fn, user_id: str, workflow_id: str, *args):
    """Enqueue `fn(*args)` on the queue, partitioned by `user_id`, under a deterministic workflow
    id (the same id runs once; DBOS hands back the first handle)."""
    if _queue is None:
        raise RuntimeError("the Bot queue is not registered")
    with SetWorkflowID(workflow_id), SetEnqueueOptions(queue_partition_key=user_id):
        return _queue.enqueue(fn, *args)


def _max_seqs(conn, user_id: str) -> tuple[int, int]:
    r = fetch_one(
        conn,
        "select (select coalesce(max(seq), 0) from wiki_event where user_id = %s) as w, "
        "(select coalesce(max(seq), 0) from aspect_event where user_id = %s) as a",
        (user_id, user_id))
    return r["w"], r["a"]


def notify(user_id: str) -> None:
    """A wake-up after a request that may have produced Bot-relevant events. Flood-guarded; the
    workflow id carries the current event seqs, so an unchanged state is enqueued once.
    Never raises."""
    try:
        rt = _rt()
        now = rt.clock()
        with rt.pool.connection() as conn, conn.transaction():
            recent = store_bot.recent_checks(conn, user_id, now - FLOOD_WINDOW)
            ok = allow_check(recent, now)
            store_bot.record_check(conn, user_id, now, dropped=not ok)
            wiki_seq, aspect_seq = _max_seqs(conn, user_id)
        if not ok:
            log.warning("bot check for %s dropped by the flood guard (the sweep catches up)",
                        user_id)
            return
        enqueue(bot_check, user_id, f"bot:check:{user_id}:{wiki_seq}:{aspect_seq}", user_id)
    except Exception:
        log.exception("bot notify failed for %s", user_id)


# --- steps ---------------------------------------------------------------------------------

def _safe(fn: Callable[[], Any]) -> Any:
    try:
        return fn()
    except Exception as exc:
        log.exception("bot step failed")
        return {"error": "internal", "detail": str(exc)[:500]}


class RsiCycleFailed(RuntimeError):
    """bot_rsi: the cycle ran but its improvement round failed on a provider / infra error; raised so
    `_recorded` marks the run failed and checks the failure streak."""


def _ok(name: str, result: Any) -> Any:
    if isinstance(result, dict) and "error" in result:
        raise RuntimeError(f"{name}: {result.get('detail', result['error'])}")
    return result


def _dt(v: Any) -> datetime:
    return v if isinstance(v, datetime) else datetime.fromisoformat(v)


@DBOS.step()
def _now() -> Any:
    return _safe(lambda: _rt().clock().isoformat())


def _slot_status(conn, user_id: str, slot_date: date) -> str | None:
    return store_bot.slot_status(conn, user_id, slot_date)


@DBOS.step()
def _due_slots(now_iso: str) -> Any:
    """Record this minute's daily slots. Returns {"slots": [[user, date, slot_at, status]] (newly
    recorded only), "enqueue": [[user, date, slot_at]] (every due slot whose row says `enqueued`,
    new or from an earlier run of this step: the workflow id dedups, so re-enqueueing is free and
    a step re-run after its commit cannot lose a daily), "errors": [...]}. One failing user does
    not hide the rest."""
    def run():
        rt = _rt()
        now = _dt(now_iso)
        out, to_enqueue, errors = [], [], []
        with rt.pool.connection() as conn:
            users = store_bot.last_seen(conn)
        for user, seen in users.items():
            try:
                with rt.pool.connection() as conn, conn.transaction():
                    settings = store_bot.get_settings(conn, user)
                    if not bot_serves(settings, seen, now):
                        log.debug("bot slots: %s is not served, no daily slot recorded", user)
                        continue
                    for slot in daily_slots(now, settings):
                        if slot_decision(slot, now, settings.timezone) == "run":
                            status, reason = "enqueued", ""
                        else:
                            status, reason = "missed", "past_date"
                        new = store_bot.record_slot(conn, user, slot.local_date, status, reason,
                                                    slot.at, now)
                        if new:
                            out.append([user, slot.local_date.isoformat(),
                                        slot.at.isoformat(), status])
                        if status == "enqueued" and (new or _slot_status(
                                conn, user, slot.local_date) == "enqueued"):
                            to_enqueue.append([user, slot.local_date.isoformat(),
                                               slot.at.isoformat()])
            except Exception as exc:
                log.exception("bot slots failed for %s", user)
                errors.append(f"{user}: {str(exc)[:200]}")
        return {"slots": out, "enqueue": to_enqueue, "errors": errors}
    return _safe(run)


@DBOS.step()
def _undispatched(now_iso: str) -> Any:
    return _safe(lambda: [list(p) for p in pipeline.undispatched(_rt().pool, now=_dt(now_iso))])


RSI_STALE = timedelta(minutes=10)


@DBOS.step()
def _stale_rsi(now_iso: str) -> Any:
    """(user, trigger) of triggers `awaiting_rsi` for over 10 minutes with no rsi run running
    (their workflow was lost): the sweep enqueues a fresh run (run_rsi changes nothing for a
    trigger that is no longer waiting)."""
    def run():
        with _rt().pool.connection() as conn:
            rows = store_bot.awaiting_rsi_triggers(conn, _dt(now_iso) - RSI_STALE)
        # a run still queued or running in DBOS (its bot_run row not written yet) is not lost
        return [[r.user_id, r.trigger_id] for r in rows if not _rsi_live(r.trigger_id)]
    return _safe(run)


def _rsi_live(trigger_id: str) -> bool:
    return any(w.status in LIVE_WORKFLOW
               for w in DBOS.list_workflows(workflow_id_prefix=rsi_id(trigger_id, "")))


@DBOS.step()
def _retry_path_edits(now_iso: str) -> Any:
    """Bot path edits left `approved` (a crash between the card's commit and their execution, or
    a raising approve) are executed (exactly once: the ledger's effect). Returns how many."""
    def run():
        rt = _rt()
        if rt.actions is None:
            return 0
        rows = pipeline.stale_path_edits(rt.pool, now=_dt(now_iso))
        for act in rows:
            pipeline.execute_path_edit(rt.pool, rt.actions, act)
        return len(rows)
    return _safe(run)


@DBOS.step()
def _rsi(trigger_id: str, run_id: str, now_iso: str) -> Any:
    """Run the user's RSI cycle for the trigger (pipeline.run_rsi). Returns the trigger's status
    afterwards; `{"error": ...}` when the runner raised (the trigger is already `failed`)."""
    def run():
        rt = _rt()
        out = pipeline.run_rsi(rt.pool, trigger_id, rt.rsi, now=_dt(now_iso), run_id=run_id)
        return {"status": out.status, "detail": out.detail, "ran": out.ran,
                "failed_b": out.error}   # not "error": `_ok` reads that key as a step failure
    return _safe(run)


LIVE_WORKFLOW = ("PENDING", "ENQUEUED")


@DBOS.step()
def _served_users(now_iso: str) -> Any:
    """The users the Bot works for right now (`bot_serves`)."""
    def run():
        now = _dt(now_iso)
        with _rt().pool.connection() as conn:
            return [u for u, seen in store_bot.last_seen(conn).items()
                    if bot_serves(store_bot.get_settings(conn, u), seen, now)]
    return _safe(run)


@DBOS.step()
def _scan(user_id: str, now_iso: str) -> Any:
    def run():
        rt = _rt()
        return pipeline.scan_events(rt.pool, user_id, now=_dt(now_iso), new_id=rt.new_id)
    return _safe(run)


@DBOS.step()
def _daily(user_id: str, local_date: str, slot_at: str, now_iso: str) -> Any:
    def run():
        rt = _rt()
        slot = Slot(date.fromisoformat(local_date), _dt(slot_at))
        return pipeline.run_daily(rt.pool, user_id, slot, now=_dt(now_iso), new_id=rt.new_id)
    return _safe(run)


@DBOS.step()
def _dispatch(trigger_id: str, now_iso: str) -> Any:
    def run():
        rt = _rt()
        out = asdict(pipeline.dispatch(rt.pool, trigger_id, now=_dt(now_iso), new_id=rt.new_id,
                                       ledger=rt.actions, gateway=rt.gateway))
        if out["status"] == "awaiting_rsi":   # enqueued on this partition
            with rt.pool.connection() as conn:
                out["user_id"] = store_bot.get_trigger(conn, trigger_id).user_id
        return out
    return _safe(run)


def _dispatch_all(name: str, ids: list[str], now_iso: str) -> None:
    """Dispatch every id even when one fails, then raise so the workflow is marked ERROR. A
    trigger left `awaiting_rsi` gets its RSI workflow enqueued on the user's partition (the id
    dedups; the sweep re-enqueues a run that was lost)."""
    failures = []
    for tid in ids:
        r = _dispatch(tid, now_iso)
        if isinstance(r, dict) and "error" in r:
            failures.append(f"{tid}: {r['detail']}")
        elif r["status"] == "awaiting_rsi":
            enqueue(bot_rsi, r["user_id"], rsi_id(tid, r["rsi_attempt"]), tid)
    if failures:
        raise RuntimeError(f"{name}: dispatch failed: " + "; ".join(failures))


@DBOS.step()
def _start_run(run_id: str, kind: str, user_id: str | None, trigger_id: str | None,
               now_iso: str) -> Any:
    """Insert the `running` row; returns the user id (a dispatch workflow knows only its
    trigger)."""
    def run():
        rt = _rt()
        uid = user_id
        if uid is None:
            with rt.pool.connection() as conn:
                t = store_bot.get_trigger(conn, trigger_id)
            if t is None:
                raise ValueError(f"unknown bot trigger {trigger_id!r}")
            uid = t.user_id
        runs.start_run(rt.pool, run_id=run_id, user_id=uid, kind=kind, trigger_id=trigger_id,
                       now=_dt(now_iso))
        return uid
    return _safe(run)


@DBOS.step()
def _finish_run(run_id: str, status: str, detail: str, now_iso: str) -> Any:
    def run():
        runs.finish_run(_rt().pool, run_id, status=status, now=_dt(now_iso), detail=detail)
        return True
    return _safe(run)


@DBOS.step()
def _pause_kind(user_id: str, kind: str, now_iso: str) -> Any:
    """After a failed run: pause the kind when it failed `failure_streak` times in a row (logged
    only). Returns the pause end (ISO) or None."""
    def run():
        rt = _rt()
        with rt.pool.connection() as conn:
            settings = store_bot.get_settings(conn, user_id)
        until = runs.pause_after_failure(rt.pool, user_id, kind, now=_dt(now_iso),
                                         settings=settings)
        return None if until is None else until.isoformat()
    return _safe(run)


@DBOS.step()
def _paused(user_id: str, kind: str, now_iso: str) -> Any:
    def run():
        until = runs.paused_until(_rt().pool, user_id, kind, now=_dt(now_iso))
        return None if until is None else until.isoformat()
    return _safe(run)


def _recorded(kind: str, user_id: str | None, trigger_id: str | None,
              body: Callable[[str], list]) -> list:
    """Run `body(now_iso)` inside a `bot_run` record. A failure is recorded (`failed` + the
    error text) and may pause the kind (failure streak) BEFORE the error is re-raised. A kind
    that is paused records `no_action` (PAUSED_DETAIL) and does nothing."""
    run_id = DBOS.workflow_id
    now_iso = _ok("now", _now())
    uid = _ok("start_run", _start_run(run_id, kind, user_id, trigger_id, now_iso))
    until = _ok("paused", _paused(uid, kind, now_iso))
    if until is not None:
        log.warning("bot %s run %s of %s skipped until %s: %s", kind, run_id, uid, until,
                    runs.PAUSED_DETAIL)
        _ok("finish_run", _finish_run(run_id, "no_action", runs.PAUSED_DETAIL, now_iso))
        return []
    try:
        ids = body(now_iso)
    except Exception as exc:
        try:
            at = _ok("now", _now())
            _ok("finish_run", _finish_run(run_id, "failed", str(exc)[:500], at))
            _ok("pause_kind", _pause_kind(uid, kind, at))
        except Exception:
            log.exception("bot run %s: recording the failure failed", run_id)
        raise
    _ok("finish_run", _finish_run(run_id, "ok" if ids else "no_action", "",
                                  _ok("now", _now())))
    return ids


def _kick_idle_writes(users: list) -> None:
    """The idle Bot's page writing, for the users it serves (it starts nothing for a user who is busy,
    has it off or nothing to write). Off the workflow: starting a page run from a workflow body would
    be recorded as one of its steps and break a replay. Lost with the process; the next sweep does it."""
    queue = _rt().write_queue
    if queue is None:
        return

    def run() -> None:
        for user in users:
            try:
                queue.kick(user)
            except Exception:
                log.exception("idle page writing for %s failed", user)
    threading.Thread(target=run, name="bot-idle-write", daemon=True).start()


# --- workflows -----------------------------------------------------------------------------

@DBOS.workflow()
def bot_tick(scheduled_at: Any, context: Any = None) -> list:
    if _bot_off("tick"):
        return []
    if lifecycle.drained():   # a restart is pending: take no new background work (spec §5.3)
        return []
    at = _dt(scheduled_at)
    now_iso = _ok("now", _now())
    if at.tzinfo is None:
        at = at.replace(tzinfo=UTC)
    # Only the DBOS scheduler's own runs (`sched-bot:tick-...`) carry a real wall-clock
    # `scheduled_at`; a directly started tick (tests, tools) names its own time. The scheduler's
    # time is compared with real time, not the injected clock.
    if (DBOS.workflow_id or "").startswith(f"sched-{SCHEDULE_NAME}-")             and datetime.now(UTC) - at > TICK_MAX_AGE:
        log.warning("bot tick %s scheduled for %s skipped: older than %s (a leftover, not "
                    "backfilled)", DBOS.workflow_id, at.isoformat(), TICK_MAX_AGE)
        return []
    res = _ok("due_slots", _due_slots(now_iso))
    for user, local_date, slot_at in res["enqueue"]:
        enqueue(bot_daily, user, f"bot:slot:daily:{user}:{local_date}", user, local_date, slot_at)
    if at.minute % SWEEP_EVERY_MINUTES == 0:
        stamp = f"{at:%Y%m%dT%H%M}"
        for user, tid in _ok("undispatched", _undispatched(now_iso)):
            enqueue(bot_dispatch, user, f"bot:dispatch:{tid}:{stamp}", tid)
        _ok("path_edits", _retry_path_edits(now_iso))
        for user, tid in _ok("stale_rsi", _stale_rsi(now_iso)):
            enqueue(bot_rsi, user, rsi_id(tid, f"sweep-{stamp}"), tid)
        served = _ok("served", _served_users(now_iso))
        for user in served:
            enqueue(bot_check, user, f"bot:sweep:{user}:{stamp}", user)
        _kick_idle_writes(served)
    if res["errors"]:
        raise RuntimeError("bot_tick: slots failed: " + "; ".join(res["errors"]))
    return [[u, d, s] for u, d, _, s in res["slots"]]



@DBOS.workflow()
def bot_check(user_id: str) -> list:
    if _bot_off("check"):
        return []
    def body(now_iso: str) -> list:
        ids = _ok("scan_events", _scan(user_id, now_iso))
        _dispatch_all("bot_check", ids, now_iso)
        return ids
    return _recorded("check", user_id, None, body)


@DBOS.workflow()
def bot_daily(user_id: str, local_date: str, slot_at: str) -> list:
    if _bot_off("daily"):
        return []
    def body(now_iso: str) -> list:
        ids = _ok("run_daily", _daily(user_id, local_date, slot_at, now_iso))
        _dispatch_all("bot_daily", ids, now_iso)
        return ids
    return _recorded("daily", user_id, None, body)


@DBOS.workflow()
def bot_dispatch(trigger_id: str) -> None:
    if _bot_off("dispatch"):
        return
    def body(now_iso: str) -> list:
        _dispatch_all("bot_dispatch", [trigger_id], now_iso)
        return [trigger_id]
    _recorded("dispatch", None, trigger_id, body)


@DBOS.workflow()
def bot_rsi(trigger_id: str) -> list:
    """B5c: one RSI cycle for an `awaiting_rsi` strategy_negative trigger, recorded as a
    `bot_run` of kind `rsi` (id = this workflow id): a cycle that ran is `ok`; manual / busy /
    no runner / not waiting any more is `no_action`; a raising runner, or a cycle whose improvement
    round failed on a provider / infra error (`error`: the trigger is already `failed`), is
    `failed` (and may pause the kind)."""
    if _bot_off("rsi"):
        return []
    def body(now_iso: str) -> list:
        r = _ok("rsi", _rsi(trigger_id, DBOS.workflow_id, now_iso))
        if r.get("failed_b"):
            raise RsiCycleFailed(f"bot trigger {trigger_id}: {r['detail']}")
        return [trigger_id] if r["ran"] else []
    return _recorded("rsi", None, trigger_id, body)
