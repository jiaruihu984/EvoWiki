log = logging.getLogger(__name__)
NEXT_TRIES = 3          # 「下一页」 plans again when the path / ledger moved under it


def _record(state: WikiState, path_id: str) -> PathRecord:
    rec = state.paths.get(path_id)
    if rec is None:
        raise LookupError(f"没有这条学习路径：{path_id}")
    return rec


def _states(state: WikiState, k: AspectK, rec: PathRecord, now: datetime,
            runs: Mapping[str, PageRunRow]) -> dict[str, tuple[PageState, WriteProgressOut | None]]:
    """Row key -> (state, write progress) (`progress.row_states`)."""
    return progress.row_states(progress.Ctx(state, AspectKView(k, now), runs), rec)


def ahead_pages(store: PageRunStore, user_id: str, state: WikiState) -> dict[str, PageRunRow]:
    """The pages the idle Bot wrote (or is writing, or failed to write) ahead that nobody has read:
    wiki page id -> its latest run. Such a page is still new to the reader, so 「下一页」 hands it
    back instead of passing it (a run the reader took over, a page opened, or in the trash is not
    ahead)."""
    ids = [pid for rec in state.paths.values() for pid in rec.page_ids
           if pid is not None and pid not in state.opened_at and pid not in state.trashed_pages]
    runs = store.latest_of(user_id, ids)
    return {pid: r for pid, r in runs.items()
            if r.origin == "idle" and r.consumed_at is None and r.discarded_at is None}


def next_item(rec: PathRecord, ahead: Collection[str] = ()) -> Item | None:
    """The first startable page that is new to the reader: no wiki page yet, or written ahead."""
    return next((i for i in _startable(rec)
                 if (pid := rec.page_ids[_stored_index(rec, i.key)]) is None or pid in ahead),
                None)


def _next_index(rec: PathRecord, ahead: Collection[str] = ()) -> int | None:
    """The stored (1-based) index of the page 「下一页」 starts."""
    item = next_item(rec, ahead)
    return None if item is None else _stored_index(rec, item.key) + 1


def _with_wiki_status(rec: PathRecord) -> LearningPath:
    """The stored path where every page that already has a wiki page counts as at least
    learning, so such a page is never picked again by next_page and refresh can mark it done."""
    pages = tuple(p.model_copy(update={"status": PageStatus.LEARNING})
                  if pid is not None and p.status is PageStatus.NOT_STARTED else p
                  for p, pid in zip(rec.path.pages, rec.page_ids, strict=True))
    return rec.path.model_copy(update={"pages": pages})


def exam_of(nodes: Sequence[str], counts: Mapping[str, int]) -> int:
    """The most exam items one of `nodes` has; 0 below EXAM_FREQUENT (not 常考)."""
    top = max((counts.get(n, 0) for n in nodes), default=0)
    return top if top >= EXAM_FREQUENT else 0


def path_out(state: WikiState, k: AspectK, path_id: str, now: datetime, *,
             user_id: str = "", prefetch: PrefetchOut | None = None,
             ahead: Collection[str] = (),
             section_labels: Mapping[str, list[str]] | None = None,
             sources: Sequence[GoalSourceOut] = (),
             exam_counts: Mapping[str, int] = {},
             runs: Mapping[str, PageRunRow] = {}) -> PathOut:
    """GET /wiki/paths/{path_id} (0 calls). Unknown path → LookupError. `prefetch`: the page the
    Bot is writing ahead (`prefetch_out`); `ahead`: the pages written ahead (`ahead_pages`).
    `section_labels` / `sources`: the materials' § labels per node and this path's materials
    (`source_view.read_source_info`, read by the route), as the graph's path rows show them;
    `exam_counts`: node id -> exam items (`exam_store.exam_counts`), for `PathPageOut.exam`."""
    rec = _record(state, path_id)
    labels = section_labels or {}
    st = _states(state, k, rec, now, runs)
    order = [(_stored_index(rec, it.key) + 1, it.skipped, it.key) for it in shown(rec) if it.page is not None]
    pages = [PathPageOut(index=i, aim="" if rec.path.source == "single" else p.objective, status=progress.status_of(st[key][0], rec.page_ids[i - 1] is not None),
                         state=st[key][0], progress=st[key][1],
                         page_id=rec.page_ids[i - 1],
                         trashed=rec.page_ids[i - 1] in state.trashed_pages,
                         skipped=skipped, key=key,
                         title=p.title, abstract=p.abstract,
                         sections=list(dict.fromkeys(
                             x for n in p.targets for x in labels.get(n, ()))),
                         exam=exam_of(p.targets, exam_counts),
                         concepts=[PathConceptOut(concept_id=c, target=c in p.targets,
                                                  name=concept_name(state, c, user_id=user_id))
                                   for c in p.concepts])
             for i, skipped, key, p in ((i, sk, kk, rec.path.pages[i - 1]) for i, sk, kk in order)]
    return PathOut(path_id=path_id, goal=rec.path.goal, source=rec.path.source, pages=pages,
                   next_index=_next_index(rec, ahead), prefetch=prefetch,
                   sources=list(sources))


def path_cards(state: WikiState, k: AspectK, now: datetime,
               ahead: Collection[str] = (),
               runs: Mapping[str, PageRunRow] = {}) -> list[PathCardOut]:
    """One catalog card per path, in planning order."""
    out = []
    for pid in state.path_order:
        gs = state.goal_settings.get(pid)
        if gs is not None and gs.archived:             # taken back: not listed
            continue
        rec = state.paths[pid]
        rows = progress.path_rows(progress.Ctx(state, AspectKView(k, now), runs), rec)
        out.append(PathCardOut(path_id=pid, goal=rec.path.goal,
                               pages=sum(r.counted for r in rows),
                               done=sum(r.counted and r.done for r in rows),
                               next_index=_next_index(rec, ahead)))
    return out


def skippable(kv: AspectKView, node_ids: Sequence[str]) -> bool:
    """可以跳过 (skill design A7): K holds every cell of the row's nodes as 确定会. Only a hint on a
    row not started: K never re-orders or skips a stored path, and the row stays enterable."""
    cells = [cell_id(c, a) for c in node_ids for a in kv.aspects(c)]
    return bool(cells) and all(kv.cell(x).band is Band.KNOWN for x in cells)


def path_items(state: WikiState, rec: PathRecord, k: AspectK, now: datetime, *,
               section_labels: Mapping[str, list[str]] | None = None,
               exam_counts: Mapping[str, int] = {},
               runs: Mapping[str, PageRunRow] = {}) -> list[PathItemOut]:
    """The path as shown (plan §4 PathItemOut): the user's order, removed pages left out,
    statuses from K (`_statuses`). `section_labels`: node id -> 「§3.2」 labels (the route reads
    them); a page shows the labels of its nodes, each once. `exam_counts`: node id -> exam items;
    `exam` is the row's largest, set only from EXAM_FREQUENT on."""
    labels = section_labels or {}
    st = _states(state, k, rec, now, runs)
    kv = AspectKView(k, now)
    out = []
    for it in shown(rec):
        if it.page is None:
            out.append(PathItemOut(key=it.key, title=it.title, summary="", question=it.question, node_ids=[],
                                   status="not_started", skipped=False, mine=True, page_id=None))
            continue
        i = _stored_index(rec, it.key)
        p = it.page
        out.append(PathItemOut(key=it.key, title=row_title(state, it), summary=p.abstract or p.objective,
                               question=it.question, node_ids=list(it.node_ids),
                               status=progress.status_of(st[it.key][0], rec.page_ids[i] is not None), state=st[it.key][0],
                               progress=st[it.key][1], skipped=it.skipped,
                               mine=it.mine, page_id=rec.page_ids[i],
                               trashed=rec.page_ids[i] in state.trashed_pages,
                               skippable=(rec.page_ids[i] is None and not it.skipped
                                          and skippable(kv, it.node_ids)),
                               opened=rec.page_ids[i] in state.opened_at,
                               sections=list(dict.fromkeys(
                                   s for n in it.node_ids for s in labels.get(n, ()))),
                               exam=exam_of(it.node_ids, exam_counts)))
    return out


@dataclass(frozen=True)
class PlannedPage:
    """The page 「下一页」 starts, planned on a snapshot: its index (1-based), the reserved page id
    and the events that create it (page record, ledger change, path update)."""

    path_id: str
    index: int
    page_id: str
    events: list[WikiEvent]


def fingerprint(rec: PathRecord) -> str:
    """A path record as planned; any change (a replan, a page started) gives another one."""
    return rec.model_dump_json()


def path_folder(state: WikiState, path_id: str) -> str | None:
    """The folder of the goal this path is on (`page_folder.goal_folder`); None: the path is on no map."""
    m = next((m for m in state.maps.values() if any(n.path_id == path_id for n in m.nodes)), None)
    return None if m is None else goal_folder(state, m)


def plan_page(snap: Snapshot, path_id: str, key: str, *, now: datetime, new_id: Ids) -> PlannedPage:
    """The wiki page of the path row `key` as events (0 LLM calls, nothing stored). Unknown path or
    row → LookupError; the row has a wiki page already → WikiConflict."""
    rec = _record(snap.state, path_id)
    item = next((i for i in _startable(rec) if i.key == key), None)
    if item is None:
        raise LookupError(f"这条学习路径上没有这一页：{path_id} / {key}")
    i = _stored_index(rec, item.key)
    if rec.page_ids[i] is not None:
        raise WikiConflict("这一页已经开始了")
    base = _with_wiki_status(rec)
    pages = list(base.pages)
    pages[i] = pages[i].model_copy(update={"status": PageStatus.LEARNING})
    path = base.model_copy(update={"pages": tuple(pages)})
    # the page's place and its earlier pages as the user sees them
    order = [path.pages[_stored_index(rec, it.key)] for it in _startable(rec)]
    if not rec.edits:
        order = list(path.pages)
    in_order = path.model_copy(update={"pages": tuple(order)})
    spec = page_spec(in_order, item.key)
    page = path.pages[i]
    title = row_title(snap.state, item)   # the row's title: a one-node row is titled with the node's name
    record, evs = page_events_for(snap.state, snap.k, title=title, goal=spec.goal,
                                  concepts=page.concepts,
                                  targets=page.targets, now=now, new_id=new_id,
                                  user_id=snap.user_id, folder=path_folder(snap.state, path_id))
    ids = list(rec.page_ids)
    ids[i] = record.page_id
    evs.append(WikiEvent(event_id=new_id("wev"), ts=now, body=PathSaved(
        record=rec.model_copy(update={"path": path, "page_ids": tuple(ids)}),
        action="page_started")))
    return PlannedPage(path_id=path_id, index=i + 1, page_id=record.page_id, events=evs)


def next_path_page(repo: Repo, user_id: str, path_id: str, *, now: datetime,
                   new_id: Ids, runs: PageRunStore | None = None,
                   key: str | None = None) -> PathNextOut:
    """「下一页」: the first page new to the reader, or the row `key` when the learner picked one
    (a row that has its page already: that page). One without a wiki page becomes one (organized
    later by the usual stream); one the Bot wrote ahead (`ahead_pages`) is handed back as it is
    (`prefetched=True`: organize replays / attaches to its run, nothing is written again). 0 LLM
    calls. Unknown path or row → LookupError; every page started → WikiConflict."""
    for attempt in range(NEXT_TRIES):
        snap = repo.load(user_id)
        rec = _record(snap.state, path_id)
        ahead = ahead_pages(runs, user_id, snap.state) if runs is not None else {}
        item = next_item(rec, ahead) if key is None else next(
            (it for it in shown(rec) if it.key == key and it.page is not None), None)
        if item is None and key is not None:
            raise LookupError(f"这条路径没有这一页：{path_id} {key}")
        if item is None:
            raise WikiConflict("这条路径的页都已经开始了", code="path_already_started",
                               public_message="Every page on this path has already been started.")
        i = _stored_index(rec, item.key)
        pid = rec.page_ids[i]
        if pid is not None:
            return PathNextOut(path_id=path_id, index=i + 1, page_id=pid, prefetched=True)
        planned = plan_page(snap, path_id, item.key, now=now, new_id=new_id)
        try:
            repo.commit(snap, Commit(wiki=planned.events))
        except WikiConflict:
            # the path or the ledger moved (the Bot planned a page ahead): plan again (0 calls)
            if attempt == NEXT_TRIES - 1:
                raise
            continue
        return PathNextOut(path_id=path_id, index=planned.index, page_id=planned.page_id)
    raise AssertionError("unreachable")


def prefetch_out(ahead: Mapping[str, PageRunRow], rec: PathRecord) -> PrefetchOut | None:
    """The path's first page the Bot has written ahead and nobody has read yet, for GET
    /wiki/paths/{id}: still writing, written (`ready`) or failed."""
    for it in _startable(rec):
        i = _stored_index(rec, it.key)
        pid = rec.page_ids[i]
        row = ahead.get(pid) if pid is not None else None
        if row is not None:
            status = {"writing": "writing", "done": "ready", "failed": "failed"}[row.status]
            return PrefetchOut(index=i + 1, page_id=row.page_id, status=status)
    return None


def path_page_done(repo: Repo, user_id: str, path_id: str, index: int, *, now: datetime,
                   new_id: Ids) -> PathPageDoneOut:
    """「学完」 on page `index` (1-based) of a path: the wiki page's done mark (page.mark_done). No such path or page → LookupError; page not started → WikiConflict."""
    from evowiki.wikiapp import page as page_flow  # page imports views, views imports paths

    snap = repo.load(user_id)
    rec = snap.state.paths.get(path_id)
    if rec is None or not 1 <= index <= len(rec.page_ids):
        raise LookupError(f"没有这一页：{path_id} 第 {index} 页")
    page_id = rec.page_ids[index - 1]
    if page_id is None or page_id in snap.state.trashed_pages:
        raise WikiConflict("这一页还没开始" if page_id is None else "这一页在回收站里，要先重新写",
                           public_message="This page has not been started." if page_id is None else
                           "This page is in the trash. Restore or rewrite it before continuing.",
                           code="page_not_started" if page_id is None else "page_trashed")
    done = page_flow.mark_done(repo, user_id, page_id, now=now, new_id=new_id)
    after = repo.load(user_id)
    return PathPageDoneOut(path=path_out(after.state, after.k, path_id, now, user_id=user_id),
                           done=done)


# --- replanning (plan T7) ---------------------------------------------------------------------

def _replan_goal(state: WikiState, k: AspectK, rec: PathRecord, now: datetime) -> IntakeResult:
    """The path's goal rebuilt from what it stores: its concept snapshot (concepts only on the
    user's own pages left out), with today's ordering edges — the node graph's prerequisite and
    recommended relations with `verified` (`order_relations`; hard only when a verified
    prerequisite) for nodes in the graph, else the snapshot's prereqs (soft) — and K's aspects.
    Targets: the concepts nothing else builds on (the intake's targets are not stored)."""
    own = {e.page_key for e in rec.edits if e.op in ("add", "want")}
    planned = {c for p in rec.path.pages if p.page_id not in own for c in p.concepts}
    snap = [c for c in rec.path.concepts if c.id in planned] or list(rec.path.concepts)
    ids = {c.id for c in snap}
    kv = AspectKView(k, now)
    rels = order_relations(state, ids)

    def prereqs(c) -> tuple[str, ...]:
        if state.graph.node(c.id) is not None:
            return ()                                   # the graph's edges are in `rels`
        return tuple(p for p in c.prereqs if p in ids and p != c.id)

    used = {p for c in snap for p in prereqs(c)} | {r.src for r in rels if r.dst != r.src}
    targets = tuple(c.id for c in snap if c.id not in used) or (snap[-1].id,)
    concepts = tuple(IntakeConcept(id=c.id, name=c.name, aspects=kv.aspects(c.id),
                                   prereqs=prereqs(c),
                                   subitems=tuple(Subitem(aspect=a, name=n)
                                                  for a, ns in c.subitems.items() for n in ns),
                                   target=c.id in targets, reused=True,
                                   definition=n.definition if (n := state.graph.node(c.id))
                                   else c.definition)
                     for c in snap)
    return IntakeResult(goal=rec.path.goal, title="", concepts=concepts, targets=targets,
                        observations=(), dropped=(), resolutions=(), relations=rels)


def replan(repo: Repo, gw: CountingGateway, user_id: str, path_id: str, *, now: datetime,
           new_id: Ids) -> PathEditOut:
    """Plans the path again (goals.path.plan_path with the stored path as `previous`: its started
    pages are carried and count as taught; 0 or more LLM calls) and merges the proposal with the
    user's edits (goals.path_edit.merge_replan: the user's work is kept). One PathSaved
    (replanned). Unknown path → LookupError. No automatic trigger."""
    snap = repo.load(user_id)
    rec = _record(snap.state, path_id)
    goal = _replan_goal(snap.state, snap.k, rec, now)
    others = snap.state.model_copy(update={
        "path_order": tuple(p for p in snap.state.path_order if p != path_id)})
    previous = _with_wiki_status(rec).model_copy(update={"goal_key": ""})
    # one run for the plan and the commit (current_run_id() at the commit point)
    with traced_step(PATH_STEP, path_id, user_id):
        proposal = traced_plan(user_id, path_id, GatewayJsonLLM(gw, subject=user_id),
                               lambda llm: plan_path(
                                   goal, AspectKView(snap.k, now), llm, previous=previous,
                                   language=snap.state.language,
                                   existing=_existing_lines(others), taught=_taught(snap.state)))
        merged = merge_replan(rec, proposal)
        new = rec.model_copy(update={"path": merged.path, "page_ids": merged.page_ids,
                                     "edits": merged.edits})
        repo.commit(snap, Commit(wiki=[WikiEvent(event_id=new_id("wev"), ts=now, body=PathSaved(
            record=new, action="replanned"))]))
    log.info("replanned %s/%s: %d pages shown, dropped %s", user_id, path_id,
             len(shown(new)), list(merged.dropped))
    return PathEditOut(path=path_items(snap.state, new, snap.k, now))
