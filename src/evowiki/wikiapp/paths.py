"""Learning paths in the wiki app (spec §9.2): GET a path, 「下一页」, 「学完」 on a path page,
catalog cards. A path is planned when a map node is opened (goal.enter_region); a page is created only when the user asks
(next_path_page: 0 LLM calls) and then generated by the ordinary organize stream.

Write-all (2026-10-15 §4): the idle Bot writes the next unwritten page of an active path
(`wikiapp.write_queue`); the page is a wiki page committed when it is written. 「下一页」 therefore
opens the first page of the path that is still new to the reader: a page without a wiki page is
created (and written by the organize stream that follows), a page the Bot wrote ahead and nobody has
read (`ahead_pages`: its latest run is the Bot's, not consumed, the page not opened) is only handed
back — organize replays / attaches to that run, no new write.

Shown states come from `wikiapp.progress` (the one source of progress): each row's `state`
(planned / writing / written / read / mastered / failed / trashed) and the older `status`
derived from it (`progress.status_of`). `runs`: the latest write run of each page
(`PageRunStore.latest_of`), read by the route; without it no row shows writing / failed.

User edits (unified node graph T7, goals.path_edit): the order shown is the stored pages with the
user's edits replayed (`shown`); 「下一页」, the prefetch and `next_index` follow it and pass over
removed and skipped pages and the user's title-only pages (nothing to teach). Indices
(`PathPageOut.index`, `PathNextOut.index`, 「学完」) stay the page's stored position, so they do
not move when the user reorders. Without edits everything is as before."""

