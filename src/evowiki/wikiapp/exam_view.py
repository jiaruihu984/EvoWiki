"""真题 on a page (materials phase 5, plan decisions 10, 11, 13).

GET /wiki/pages/{id}/exam: the ok items attached to the page's target / concept nodes (materials
not deleted), in material order. Objective items with a key go into one EvoUI quiz (layout paged,
at most EXAM_QUIZ_SIZE; the ones past that stay in the native list),
stored as an `evoui` asset on demand: job_id `exam:<page_id>:<h>` with h = sha1 of the block JSON
(an asset with that job is reused; `wiki_asset` is append-only), on the page's last section. The
block is generated by code, so it gets no browser render check. Everything else (open questions,
objective ones without a key, any question the block validator refuses) is listed for the plugin
to draw natively: fail closed, but no question is lost. Quiz answers are graded by the existing
POST /wiki/assets/{id}/results (`block_results`).

POST /wiki/exam/items/{id}/self: 「我答对了」 / 「没答对」 on a keyed item is a weak self-report in
K (kind self, strength 0.5, `+` / `~`, evidence_ref `exam:<item>:<YYYY-MM-DD>`, once a day per
item) when its cell is a K cell, run through the one K-change pass without a gateway (folds /
section marks of the item's page, other pages stale), else only recorded ("score"); either way a
`block_result` signal (outcome 1 / 0) on the item's page. 「做完了」 records no evidence. Every report
is a `source_item_mark` row, key `exam:<item>:<date>` for right / wrong (one graded report a day,
the unique key enforces it) and `exam:<item>:<date>:done`; the day is the user's local day (Bot
time zone). Any report marks the item done for the day. 0 LLM calls."""

