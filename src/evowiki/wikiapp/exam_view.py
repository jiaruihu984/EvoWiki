log = logging.getLogger(__name__)

EXAM_QUIZ_SIZE = 15                  # questions in the page's exam quiz (the rest stay in the list)
QUIZ_TITLE = "真题练习"
QUIZ_QUESTION = "用往年真题检查这一页学到的东西"
QUIZ_NODE_ID = "exam"
ASSET_HEIGHT = 400
SELF_STRENGTH = 0.5
SELF_QUOTE = {"right": "我答对了", "wrong": "没答对"}
SELF_ACTION = "exam_self"
UNATTACHED_SHOWN = 20
STEM_HEAD = 60
LABEL_MAX = 600
MSG_NO_PAGE = "找不到这一页"
MSG_NO_ITEM = "没有这道题"
MSG_NO_KEY = "这道题没有答案，只能标做完"
MSG_RACE = "这道题刚刚已经记过了"
_OBJECTIVE = ("single", "multi", "tf")
_TF = ("对", "错")
_GENERATED = "generated by code: no browser render check"


# ---- the quiz block ----

def _js_len(s: str) -> int:
    return len(s.encode("utf-16-le")) // 2


def _clip(s: str, n: int) -> str:
    """`s` cut to at most `n` UTF-16 units (as the block validator counts), with … when cut."""
    if _js_len(s) <= n:
        return s
    while s and _js_len(s) + 1 > n:
        s = s[:-1]
    return s + "…"


def _letters(answer: str | None, n_options: int) -> list[int] | None:
    if not answer:
        return None
    idx = [ord(ch) - ord("A") for ch in answer.strip().upper()]
    if not idx or any(not 0 <= i < n_options for i in idx) or len(set(idx)) != len(idx):
        return None
    return idx


def _correct(it: ExamItem) -> int | list[int] | None:
    """The block's `correct`: single an option index, multi a sorted index list, tf 0 对 / 1 错."""
    if it.kind == "tf":
        a = (it.answer or "").strip()
        return _TF.index(a) if a in _TF else None
    idx = _letters(it.answer, len(it.options))
    if idx is None:
        return None
    if it.kind == "single":
        return idx[0] if len(idx) == 1 else None
    return sorted(idx)


def _q_text(it: ExamItem, group: ExamItem | None) -> str:
    """The question text: the 大题 passage first (「材料：…」, cut so the stem stays whole)."""
    if group is None or not group.stem.strip():
        return _clip(it.stem, MAX_TEXT_CHARS)
    head, tail = "材料：", "\n\n" + it.stem
    room = MAX_TEXT_CHARS - _js_len(head) - _js_len(tail)
    if room < 20:                       # no room for a useful passage
        return _clip(it.stem, MAX_TEXT_CHARS)
    return head + _clip(group.stem, room) + tail


def _option_text(i: int, option: str) -> str:
    """An option without its own printed label (「A. 1」 → 「1」, also A、 A： (A) （A） A)): the quiz
    draws the letters itself. Only the label of its own position is taken off; an option that
    would be left empty keeps its text."""
    letter = chr(ord("A") + i)
    m = re.match(rf"\s*(?:[(（]\s*{letter}\s*[)）]|{letter}\s*[.．、:：)）])\s*", option)
    rest = option[m.end():] if m else option
    return rest if rest.strip() else option


def _why(it: ExamItem, cite: str | None) -> str:
    if it.explanation and it.explanation.strip():
        return _clip(it.explanation.strip(), MAX_TEXT_CHARS)
    where = f"（见{cite}）" if cite else ""
    return _clip(f"答案：{it.answer}{where}", MAX_TEXT_CHARS)


def _question(it: ExamItem, group: ExamItem | None, cite: str | None) -> dict | None:
    """One quiz question for a keyed objective item; None when its key does not fit its options."""
    if it.kind not in _OBJECTIVE or not it.has_key:
        return None
    correct = _correct(it)
    if correct is None:
        return None
    q: dict = {"q": _q_text(it, group), "options": list(_TF) if it.kind == "tf"
         else [_option_text(i, o) for i, o in enumerate(it.options)],
               "correct": correct, "why": _why(it, cite)}
    if it.kind != "single":
        q["type"] = it.kind
    if it.cell and CELL_RE.match(it.cell):
        q["cell"] = it.cell
    return q


def _fallback(items: Sequence[ExamItem]) -> str:
    lines = []
    for i, it in enumerate(items, start=1):
        lines.append(f"{i}. {it.stem}")
        opts = _TF if it.kind == "tf" else it.options
        lines += [f"   {o}" for o in opts]
    return _clip("\n".join(lines), MAX_FALLBACK_CHARS)


def quiz_block(items: Sequence[ExamItem], groups: Mapping[str, ExamItem], title: str, *,
               cite: Mapping[str, str] | None = None) -> dict:
    """The EvoUI block of `items` (keyed objective items, at most EXAM_QUIZ_SIZE): one paged quiz
    node 「真题练习」. `groups`: group item_id -> group (the 大题 passages); `cite`: item_id ->
    「《资料》p.12」 for a key without an explanation. ValueError for an item that cannot be a
    quiz question."""
    cite = cite or {}
    qs = []
    for it in items:
        q = _question(it, groups.get(it.parent_id or ""), cite.get(it.item_id))
        if q is None:
            raise ValueError(f"item {it.item_id} is not a keyed objective question")
        qs.append(q)
    return {"type": "evoui", "title": _clip(title, 120), "question": QUIZ_QUESTION,
            "state": {}, "derived": {},
            "body": {"kind": "quiz", "id": QUIZ_NODE_ID, "layout": "paged", "title": QUIZ_TITLE,
                     "questions": qs},
            "fallback": _fallback(items)}


def _block_problems(block: dict) -> list[str]:
    errs = validate_block(block)
    try:
        EvoUIBlock.model_validate(block)
    except ValidationError as exc:
        errs.append(str(exc)[:300])
    return errs


# ---- GET /wiki/pages/{id}/exam ----

def _cite(src: SourceRow | None, it: ExamItem) -> str | None:
    if src is None:
        return None
    if it.page is None:
        return f"《{src.title}》"
    shown = printed_page(it.page, src.page_offset)
    return f"《{src.title}》p.{shown if shown is not None else it.page}"


def _open_out(it: ExamItem, group: ExamItem | None, src: SourceRow | None,
              done: bool) -> ExamOpenItemOut:
    shown = (printed_page(it.page, src.page_offset)
             if it.page is not None and src is not None else None)
    return ExamOpenItemOut(
        item_id=it.item_id, number=it.number, context=group.stem if group is not None else None,
        stem=it.stem, options=[_option_text(i, o) for i, o in enumerate(it.options)], kind=it.kind,  # type: ignore[arg-type]
        has_key=it.has_key, answer=it.answer if it.has_key else None,
        explanation=it.explanation, source_title=src.title if src is not None else "",
        page=it.page, printed_page=str(shown) if shown is not None else None, done=done)


def page_nodes(snap: Snapshot, page_id: str) -> list[str]:
    rec = snap.state.pages.get(page_id)
    if rec is None:
        raise LookupError(MSG_NO_PAGE)
    return list(dict.fromkeys((*rec.targets, *rec.concepts)))


def page_exam(conn: psycopg.Connection, repo_snapshot: Snapshot, assets: AssetStore, user_id: str,
              page_id: str, *, now: datetime, new_id: Ids) -> PageExamOut:
    """See the module doc. LookupError for an unknown page."""
    snap = repo_snapshot
    nodes = page_nodes(snap, page_id)
    rec = snap.state.pages[page_id]
    items = [it for it in exam_store.items_for_nodes(conn, user_id, nodes) if it.kind != "group"]
    frequent = bool(exam_store.frequent_nodes(exam_store.exam_counts(conn, user_id)) & set(nodes))
    if not items:
        return PageExamOut(asset_id=None, quiz_count=0, open_items=[], sources=[],
                           frequent=frequent)
    parents = sorted({it.parent_id for it in items if it.parent_id})
    groups = {g.item_id: g for g in exam_store.items_by_id(conn, user_id, parents)}
    srcs = {sid: store.get_source(conn, user_id, sid)
            for sid in dict.fromkeys(it.source_id for it in items)}
    cite = {it.item_id: c for it in items if (c := _cite(srcs[it.source_id], it)) is not None}

    # the quiz: keyed objective items whose question passes the validator on its own
    sections = rec.page.outline.sections if rec.page is not None else ()
    quiz: list[ExamItem] = []
    if sections:
        for it in items:
            if _question(it, groups.get(it.parent_id or ""), cite.get(it.item_id)) is None:
                continue
            errs = _block_problems(quiz_block([it], groups, QUIZ_TITLE, cite=cite))
            if errs:
                log.info("exam item %s/%s does not fit a quiz: %s", user_id, it.item_id,
                         "; ".join(errs)[:300])
            elif len(quiz) < EXAM_QUIZ_SIZE:
                quiz.append(it)
    asset_id = None
    if quiz:
        block = quiz_block(quiz, groups, QUIZ_TITLE, cite=cite)
        errs = _block_problems(block)
        if errs:
            log.warning("exam quiz for page %s/%s refused by the validator, listing the items "
                        "instead: %s", user_id, page_id, "; ".join(errs)[:500])
            quiz = []
        else:
            asset_id = _asset(conn, assets, user_id, page_id, sections[-1].id, block, now=now,
                              new_id=new_id)
    hidden = {it.item_id for it in quiz}
    shown = [it for it in items if it.item_id not in hidden]
    marks = exam_store.marks_on(conn, user_id, [it.item_id for it in shown],
                                local_day(conn, user_id, now))
    return PageExamOut(
        asset_id=asset_id, quiz_count=len(quiz),
        open_items=[_open_out(it, groups.get(it.parent_id or ""), srcs[it.source_id],
                              bool(marks.get(it.item_id))) for it in shown],
        sources=[s.title for s in srcs.values() if s is not None], frequent=frequent)


def _asset(conn: psycopg.Connection, assets: AssetStore, user_id: str, page_id: str,
           section_id: str, block: dict, *, now: datetime, new_id: Ids) -> str:
    """The stored quiz asset of this exact block (reused when there), else a new one written and
    committed on `conn`."""
    content = block_json(block)
    h = hashlib.sha1(content.encode("utf-8")).hexdigest()[:16]
    job_id = f"exam:{page_id}:{h}"
    have = assets.by_job(user_id, job_id)
    if have is not None:
        return have.meta.asset_id
    iid = f"exam-{h}"
    asset = StoredAsset(
        user_id=user_id, created_at=now, job_id=job_id, html=content,
        meta=AssetMeta(asset_id=new_id("ia"), page_id=page_id, section_id=section_id,
                       interactive_id=iid, title=QUIZ_TITLE, height=ASSET_HEIGHT,
                       sha256=sha256(content), kind="evoui",
                       check=RenderCheck(interactive_id=iid, ok=True, detail=_GENERATED)))
    with conn.transaction():
        assets.writer([asset])(conn)
    return asset.meta.asset_id


# ---- POST /wiki/exam/items/{id}/self ----

def _label(it: ExamItem, result: str) -> str:
    return (f"真题：{it.stem}；自评「{SELF_QUOTE[result]}」；答案「{it.answer or ''}」")[:LABEL_MAX]


def self_report(repo: Repo, pool: ConnectionPool, user_id: str, item_id: str, result: str, *,
                now: datetime, new_id: Ids) -> ExamSelfOut:
    """See the module doc. LookupError: no such item of this user (or its material is deleted);
    WikiInvalid: right / wrong on an item without a key."""
    with pool.connection() as conn:
        got = exam_store.items_by_id(conn, user_id, [item_id])
    it = got[0] if got else None
    if it is None or it.kind == "group" or it.status != "ok":
        raise LookupError(MSG_NO_ITEM)
    if result != "done" and not it.has_key:
        raise WikiInvalid(MSG_NO_KEY, public_message="This question has no answer key. You can only mark it complete.", code="question_has_no_key")
    with pool.connection() as conn:
        day = local_day(conn, user_id, now)
    if result == "done":
        return ExamSelfOut(status="done" if _mark(pool, user_id, item_id, result, day, now)
                           else "duplicate")
    with pool.connection() as conn:
        have = exam_store.marks_on(conn, user_id, [item_id], day).get(item_id, set())
    if have & set(SELF_QUOTE):                         # graded once a day per item
        return ExamSelfOut(status="duplicate")
    snap = repo.load(user_id)
    page_id = _item_page(snap, it.node_id)
    aspect = []
    wiki = []
    if it.cell is not None and _known(snap, it.cell):
        obs = Observation(cell=it.cell, polarity="+" if result == "right" else "-",
                          strength=SELF_STRENGTH, kind="self",
                          evidence_ref=f"exam:{item_id}:{day.isoformat()}",
                          quote=SELF_QUOTE[result])
        aspect = observation_events([obs], ts=now, new_id=new_id,
                                    note_label=lambda _o: _label(it, result))
        # the one K-change pass, without a gateway (0 LLM calls): folds / marks of the page
        kc = k_changed(snap, apply_in_memory(snap, aspect), page_id, None,
                       skip=None, now=now, new_id=new_id, action=SELF_ACTION)
        wiki += kc.wiki
    wiki.append(signal_event(snap.state, "block_result", now=now, new_id=new_id, page_id=page_id,
                             text=_signal_text(it, result),
                             outcome=1.0 if result == "right" else 0.0))

    def write(conn: psycopg.Connection | None) -> None:
        if conn is None:                               # MemoryRepo
            fresh = _mark(pool, user_id, item_id, result, day, now)
        else:
            fresh = exam_store.add_mark(conn, user_id, item_id, result, day=day, at=now)
        if not fresh:
            raise WikiConflict(MSG_RACE)

    repo.commit(snap, Commit(aspect=aspect, wiki=wiki, extra=[write]))
    return ExamSelfOut(status="k" if aspect else "score")


def local_day(conn: psycopg.Connection, user_id: str, now: datetime) -> date:
    """The user's local day (the Bot settings' time zone, default Asia/Shanghai)."""
    return local_date(now, bot_store.get_settings(conn, user_id).timezone)


def _item_page(snap: Snapshot, node_id: str | None) -> str | None:
    """The page the item's node is on: a page targeting it first, then one covering it."""
    if node_id is None:
        return None
    live = [r for r in snap.state.pages.values() if r.page_id not in snap.state.trashed_pages]
    hit = (next((r for r in live if node_id in r.targets), None)
           or next((r for r in live if node_id in r.concepts), None))
    return hit.page_id if hit is not None else None


def _signal_text(it: ExamItem, result: str) -> str:
    head = f"第 {it.number} 题" if it.number else "真题"
    return f"真题自评：{head}「{_clip(it.stem, 200)}」{SELF_QUOTE[result]}"


def _mark(pool: ConnectionPool, user_id: str, item_id: str, result: str, day: date,
          at: datetime) -> bool:
    with pool.connection() as conn:
        return exam_store.add_mark(conn, user_id, item_id, result, day=day, at=at)


# ---- the material's exam summary (SourceDetail.exam) ----

def _unattached_line(it: ExamItem) -> str:
    stem = " ".join(it.stem.split())
    head = stem[:STEM_HEAD] + ("…" if len(stem) > STEM_HEAD else "")
    line = f"第 {it.number} 题：{head}" if it.number else head
    return f"{line}（{it.attach_note}）" if it.attach_note else line


def _no_record_state(row: SourceRow) -> tuple[str, str | None] | None:
    """The card's state before the exam workflow wrote a record: extracting only while the
    import is still running or once it ended done in full (the workflow is about to start);
    failed when the import failed (its on_ready never runs); else None (no exam line: the
    import ended in a mode that extracts nothing). Never 「正在找题」 for a run that cannot come."""
    progress = row.progress if isinstance(row.progress, dict) else {}
    if row.status == "failed" or progress.get("end") == "error":
        return "failed", DETAIL_FAILED
    if "end" not in progress or imported_in_full(progress):
        return "extracting", None
    return None


def exam_summary(conn: psycopg.Connection, user_id: str, source_id: str) -> ExamSummaryOut | None:
    """None when the material has no exam use. The state and detail come from
    `progress["exam"]` (no record yet: `_no_record_state`), the counts from the stored items."""
    row = store.get_source(conn, user_id, source_id)
    if row is None or not has_exam_use(store.uses_of(conn, user_id, source_id)):
        return None
    rec = row.progress.get("exam") if isinstance(row.progress, dict) else None
    rec = rec if isinstance(rec, dict) else {}
    if rec.get("state") in ("extracting", "done", "failed"):
        state, detail = rec["state"], rec.get("detail")
    else:
        got = _no_record_state(row)
        if got is None:
            return None
        state, detail = got
    items = exam_store.items_of_source(conn, user_id, source_id)
    counts = exam_summary_counts(items)
    lost = [it for it in items if it.kind != "group" and it.status == "ok"
            and it.attach == "unattached"]
    return ExamSummaryOut(
        state=state, items=counts["items"], attached=counts["attached"],
        unattached=counts["unattached"], pending=counts["pending"],
        unreadable=counts["unreadable"], incomplete=counts["incomplete"],
        unattached_items=[_unattached_line(it) for it in lost[:UNATTACHED_SHOWN]],
        detail=detail if isinstance(detail, str) else None)
