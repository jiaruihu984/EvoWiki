"""Synthetic preference and complaint walkthrough on a disposable scripted backend.

The utterances below were written for public regression tests. They preserve two conditions:
a lasting request for interactive examples must reach preferences, and repeated diagnosis of
an explicitly unfamiliar topic must reach report_problem. They are not exported user quotes.
The writer records the teaching spec it receives so the next write and undo can be checked.
Historical screenshots and measurements were not regenerated by this fixture replacement.
"""

