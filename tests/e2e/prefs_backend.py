LIKES = "今后讲解时，请配一两个可以操作的演示组件"
RULE = "讲解页配上一两个可以操作的演示组件"
COMPLAINT = "刚才已经选了不熟悉，这一步为什么又问相同的内容"
PROBLEM = "学习者已选不熟悉，却再次收到同一内容的诊断提问"
WRITES: list[dict] = []


class RecordingWriter(MaterialWriter):
    """MaterialWriter that keeps what each page write was given (GET /test/writes)."""

    def write(self, inp, **kw):
        WRITES.append({"page_id": inp.page_id, "items": [i.text for i in inp.teaching.items],
                       "spec": preread_spec(inp.teaching)})
        return super().write(inp, **kw)


def assistant_turn(script: FailClosedScript, request: ChatRequest) -> ChatTurn:
    msgs = request.messages
    users = [i for i, m in enumerate(msgs) if m.role == "user"]
    said = msgs[users[-1]].text if users else ""
    done = [m for m in (msgs[users[-1] + 1:] if users else ()) if m.role == "tool"]
    if LIKES in said:
        if done:
            ok = "已执行" in done[-1].text
            return ChatTurn(text="好，这页我先给你加一个能动手的小组件。" if ok
                            else f"这条没记下：{done[-1].text[:80]}")
        return ChatTurn(tool_calls=(ToolCall(id="t1", name="remember_preference",
                                             args={"applies": "lasting", "quote": LIKES,
                                                   "text": RULE}),))
    if COMPLAINT in said:
        if done:
            return ChatTurn(text="抱歉，你已经说过不会了，不该再问一遍。我们直接从最基础的讲起。")
        return ChatTurn(tool_calls=(ToolCall(id="t1", name="report_problem",
                                             args={"quote": COMPLAINT, "problem": PROBLEM}),))
    what = f"{request.purpose}/{request.subject}: {said[-60:]!r}"
    script.unscripted.append(what)
    print(f"[prefs_backend] UNSCRIPTED ASSISTANT TURN: {what}", file=sys.stderr, flush=True)
    raise Unscripted(what)


def assistant_gateway(script: FailClosedScript) -> Gateway:
    providers = {p: ScriptedChatProvider(p, lambda _m, r: assistant_turn(script, r),
                                         complete=script._responder(p)) for p in PROVIDERS}
    return Gateway(GW_CONFIG, script.log, mode="record", clock=lambda: T0, providers=providers,
                   record_max_attempts=1)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8771)
    ap.add_argument("--user", default="walk-user")
    a = ap.parse_args(argv)
    admin, _keep = start_admin_url()
    build_template(admin)
    url, _ = fresh_database(admin)
    pool = make_pool(url)
    ctx = seed_runtime(pool)
    make_user(pool, a.user)
    PgRsiStore(pool).put_settings(a.user, RsiSettings(cycle="manual"))   # TEST ONLY
    script = build_script()
    clock = SystemClock()
    ids = Ids()
    repo = PgRepo(pool)
    svc = Services(pool=pool, ctx=ctx, clock=clock, embedder=HashingEmbedder(),
                   gateway=script.gateway(), new_id=ids,
                   runs=InlinePageRuns(spawn=spawn_thread, store=PgPageRunStore(pool)),
                   page_writing=Writing(writer=RecordingWriter(), specs=WikiSpecSource(repo),
                                        assets=PgAssetStore(pool),
                                        sources=PooledSourceExcerpts(pool)))
    svc.deep = DeepService(repo=repo, jobs=PgJobStore(pool), assets=PgAssetStore(pool),
                           specs=WikiSpecSource(repo), checker=FakeChecker(), llm=None,
                           clock=clock, new_id=ids)
    svc.actions = ledger = ActionLedger(pool, clock, ids, {})
    ledger.register("stated_rule", PreferenceExecutor(repo, lambda uid: None, clock, ids))
    svc.change_sources = (LedgerChangeSource(ledger),)     # 参数 → 最近更新, as in production
    svc.assistant = build_assistant(pool, assistant_gateway(script), ctx.content, svc.embedder,
                                    clock, ids, ledger=ledger)
    app = create_app(svc)
    seeded = seed_goal(app, a.user)
    mount_script_status(app, script)

    @app.get("/test/writes")
    def _writes() -> list[dict]:
        return WRITES

    print(json.dumps({"wiki_backend": f"http://127.0.0.1:{a.port}", "user": a.user, **seeded},
                     ensure_ascii=False), flush=True)
    uvicorn.run(app, host="127.0.0.1", port=a.port, log_level="warning")


if __name__ == "__main__":
    main()
