"""The Obsidian plugin's wire types (obsidian-plugin/src/generated/*.ts) and the contract tests' JSON Schema
(obsidian-plugin/src/generated/wire-schema.json) are generated from the pydantic models by scripts/gen_plugin_types.py;
a backend model change without a regeneration fails here (no live backend, no LLM)."""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "gen_plugin_types.py"


def _gen():
    spec = importlib.util.spec_from_file_location("gen_plugin_types", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod          # dataclasses resolve the module's annotations through sys.modules
    spec.loader.exec_module(mod)
    return mod


def test_generated_plugin_types_are_fresh():
    gen = _gen()
    files = gen.generate()
    assert set(files) == {f"{a}.ts" for a in gen.AREAS} | {gen.SCHEMA_FILE}
    stale = gen.stale(files)
    assert not stale, f"stale generated plugin types: {', '.join(stale)} — run python scripts/gen_plugin_types.py"


def test_every_file_is_marked_generated():
    gen = _gen()
    for name, text in gen.generate().items():
        if name == gen.SCHEMA_FILE:
            assert json.loads(text)["$comment"].startswith("GENERATED by scripts/gen_plugin_types.py — do not edit"), name
            continue
        assert text.startswith("// GENERATED by scripts/gen_plugin_types.py — do not edit\n"), name


def test_output_is_deterministic():
    gen = _gen()
    assert gen.generate() == gen.generate()
