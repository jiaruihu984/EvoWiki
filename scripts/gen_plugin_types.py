def _annotation(cls: type[BaseModel], name: str) -> Any:
    """The field's annotation; a string forward reference pydantic kept as-is is evaluated in the model's module."""
    ann = cls.model_fields[name].annotation
    if "ForwardRef" in repr(ann):
        ann = typing.get_type_hints(cls, include_extras=True)[name]
    return ann


def _strip(tp: Any) -> Any:
    while get_origin(tp) is Annotated:
        tp = get_args(tp)[0]
    if isinstance(tp, typing.TypeAliasType):
        return _strip(tp.__value__)
    return tp


_DATES = (dt.datetime, dt.date, dt.time, pydantic.AwareDatetime, pydantic.NaiveDatetime, pydantic.PastDatetime,
          pydantic.FutureDatetime, pydantic.PastDate, pydantic.FutureDate)
_SEQ = (list, tuple, set, frozenset, collections.abc.Sequence, collections.abc.Set, collections.abc.Iterable)
_MAP = (dict, collections.abc.Mapping)


def _src(module: str) -> str:
    """evowiki.wikiapp.wiki_schemas -> wikiapp/wiki_schemas.py"""
    return module.removeprefix("evowiki.").replace(".", "/") + ".py"


def _doc(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    lines = inspect.cleandoc(text).replace("*/", "*\\/").splitlines()
    lines = [ln.rstrip() for ln in lines]
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *[f"{indent} * {ln}".rstrip() for ln in lines], f"{indent} */"]


@dataclass
class Named:
    """A named type alias (Literal / StrEnum / union) emitted once."""
    ts: str
    area: str
    origin: str
    key: Any
    body: str = ""
    doc: str | None = None
    table: str | None = None   # const table that defines it
    module: str | None = None  # the Python module that defines it


@dataclass
class ModelOut:
    cls: type[BaseModel]
    ts: str
    area: str
    bodies: dict[str, list[str]] = field(default_factory=dict)   # mode ("out" / "in") -> member lines


class Gen:
    def __init__(self) -> None:
        self.models: dict[type[BaseModel], ModelOut] = {}
        self.order: list[type[BaseModel]] = []
        self.pending: list[tuple[type[BaseModel], str]] = []
        self.sse_models: set[type[BaseModel]] = set()
        self.rest_models: set[type[BaseModel]] = set()
        self.aliases: dict[tuple[str, str], Named] = {}         # (defining module, python name) -> alias
        self.defs_by_id: dict[int, set[tuple[str, str]]] = {}   # id(alias object) -> where it is defined
        self.table_types: dict[tuple[Any, ...], Named] = {}     # members -> the type a constant table names
        self.named_enums: dict[type, Named] = {}
        self.used_named: list[Named] = []
        self.ts_names: dict[str, str] = {}                       # TS name -> origin (collision check)
        self._scan_aliases()

    # ---- names ----
    def _claim(self, ts: str, origin: str) -> None:
        prev = self.ts_names.get(ts)
        if prev is not None and prev != origin:
            raise SystemExit(f"TS name {ts!r} is used by {prev} and {origin}: add one of them to RENAMES")
        self.ts_names[ts] = origin

    @staticmethod
    def _alias_key(val: Any) -> tuple[str, Any] | None:
        """("lit", members) for `X = Literal[...]`, ("union", frozenset of members) for a discriminated
        `X = Annotated[A | B, Field(discriminator=...)]`, else None."""
        if get_origin(val) is Literal:
            return ("lit", get_args(val))
        if get_origin(val) is Annotated and get_origin(get_args(val)[0]) in (Union, types.UnionType)                 and any(getattr(m, "discriminator", None) for m in get_args(val)[1:]):
            return ("union", frozenset(get_args(get_args(val)[0])))
        return None

    @staticmethod
    def _type_attrs(mod: types.ModuleType) -> list[tuple[str, Any]]:
        return [(n, v) for n, v in sorted(vars(mod).items()) if n[:1].isupper() and not n.isupper()]

    def _scan_aliases(self) -> None:
        """Every module-level Literal / discriminated-union alias of the loaded evowiki modules, at the module whose
        source assigns it (an import elsewhere is the same object under the same name)."""
        for modname, mod in sorted(sys.modules.items()):
            if not modname.startswith("evowiki.") or mod is None:
                continue
            try:
                src = inspect.getsource(mod)
            except (OSError, TypeError):
                continue
            for name, val in self._type_attrs(mod):
                key = self._alias_key(val)
                if key is None or not re.search(rf"^{re.escape(name)}\s*(:[^=]*)?=", src, re.MULTILINE):
                    continue
                n = Named(RENAMES.get((modname, name), name), area_of(modname), f"{_src(modname)} {name}", key[1],
                          module=modname)
                self.aliases[(modname, name)] = n
                self.defs_by_id.setdefault(id(val), set()).add((modname, name))

    def _alias(self, key: tuple[str, Any], ctx: str | None) -> Named | None:
        """The alias a Literal / union is spelled with: the name the context module (where the model is defined)
        sees it under; None (inline) when it has none or several."""
        mod = sys.modules.get(ctx or "")
        if mod is not None:
            found: set[tuple[str, str]] = set()
            for name, val in self._type_attrs(mod):
                if self._alias_key(val) == key:
                    found |= {d for d in self.defs_by_id.get(id(val), ()) if d[1] == name}
            if len(found) == 1:
                return self.aliases[found.pop()]
        return None

    def register_table(self, tbl: Table, values: tuple[Any, ...]) -> None:
        if tbl.type_name is None:
            return
        if values in self.table_types:
            raise SystemExit(f"table {tbl.name}: members already named {self.table_types[values].ts}")
        self.table_types[values] = Named(tbl.type_name, tbl.area, tbl.name, values, table=tbl.name)

    def _use(self, n: Named) -> str:
        if n not in self.used_named:
            if n.table is None:   # a table's type is declared per area (assistant and wiki each have an ErrorCode)
                self._claim(n.ts, n.origin)
            self.used_named.append(n)
        return n.ts

    # ---- models ----
    def ref(self, cls: type[BaseModel], mode: str) -> str:
        if cls not in self.models:
            ts = RENAMES.get((cls.__module__, cls.__name__), cls.__name__)
            self._claim(ts, f"{_src(cls.__module__)} {cls.__name__}")
            self.models[cls] = ModelOut(cls, ts, area_of(cls.__module__))
            self.order.append(cls)
        if mode not in self.models[cls].bodies and (cls, mode) not in self.pending:
            self.pending.append((cls, mode))
        return f"\0{id(cls)}:{mode}\0"

    def drain(self) -> None:
        while self.pending:
            cls, mode = self.pending.pop(0)
            if mode in self.models[cls].bodies:
                continue
            self.models[cls].bodies[mode] = self._members(cls, mode)

    def _members(self, cls: type[BaseModel], mode: str) -> list[str]:
        out: list[str] = []
        sse = cls in self.sse_models
        for name, fi in cls.model_fields.items():
            if mode == "out" and fi.exclude:
                continue
            if mode == "in":
                wire = fi.validation_alias if fi.validation_alias is not None else fi.alias
                if wire is not None and not isinstance(wire, str):
                    raise SystemExit(f"{cls.__name__}.{name}: non-string validation alias {wire!r}")
                optional = not fi.is_required()
            else:
                rest_name = fi.serialization_alias or fi.alias or name
                sse_name = (fi.serialization_alias or fi.alias or name) if cls.model_config.get("serialize_by_alias") \
                    else name
                if sse and cls in self.rest_models and rest_name != sse_name:
                    raise SystemExit(f"{cls.__name__}.{name}: REST sends {rest_name!r}, SSE sends {sse_name!r}")
                wire = sse_name if sse else rest_name
                optional = False
            wire = wire or name
            key = wire if re.fullmatch(r"[A-Za-z_$][\w$]*", wire) else json.dumps(wire)
            out.append(f"  {key}{'?' if optional else ''}: {self.ts(_annotation(cls, name), mode, cls.__module__)};")
        if mode == "out":
            for name, cf in cls.model_computed_fields.items():
                out.append(f"  {cf.alias or name}: {self.ts(cf.return_type, mode, cls.__module__)};")
        return out

    # ---- types ----
    def ts(self, tp: Any, mode: str, ctx: str | None = None) -> str:
        tp0 = tp
        if get_origin(tp) is Annotated:
            return self.ts(get_args(tp)[0], mode, ctx)
        if isinstance(tp, typing.TypeAliasType):
            return self.ts(tp.__value__, mode, ctx)
        if tp is Any or tp is object:
            return "unknown"
        if tp is None or tp is type(None):
            return "null"
        if tp is str:
            return "string"
        if tp is bool:
            return "boolean"
        if tp in (int, float):
            return "number"
        if tp in _DATES:
            return "string"
        if tp is dict:
            return "Record<string, unknown>"
        if tp in (list, tuple):
            return "unknown[]"
        if inspect.isclass(tp) and issubclass(tp, enum.Enum):
            n = self.named_enums.get(tp)
            if n is None:
                values = tuple(m.value for m in tp)
                ts = RENAMES.get((tp.__module__, tp.__name__), tp.__name__)
                n = self.table_types.get(values)
                if n is None or n.ts != ts:
                    n = Named(ts, area_of(tp.__module__), f"{_src(tp.__module__)} {tp.__name__}", values)
                    n.doc = tp.__doc__ if tp.__doc__ and tp.__doc__ != enum.StrEnum.__doc__ else None
                self.named_enums[tp] = n
            if not n.body:
                n.body = " | ".join(json.dumps(v, ensure_ascii=False) for v in n.key)
            return self._use(n)
        if inspect.isclass(tp) and issubclass(tp, BaseModel):
            return self.ref(tp, mode)
        origin, args = get_origin(tp), get_args(tp)
        if origin is Literal:
            n = self.table_types.get(args) or self._alias(("lit", args), ctx)
            if n is not None:
                if not n.body:
                    n.body = " | ".join(json.dumps(v, ensure_ascii=False) for v in args)
                return self._use(n)
            return " | ".join(json.dumps(v, ensure_ascii=False) for v in args)
        if origin in (Union, types.UnionType):
            n = self._alias(("union", frozenset(args)), ctx)
            if n is not None:
                if not n.body:
                    n.body = " | ".join(self.ts(a, mode, n.module) for a in args)
                return self._use(n)
            parts: list[str] = []
            for a in args:
                s = self.ts(a, mode, ctx)
                if s not in parts:
                    parts.append(s)
            if "null" in parts:   # null last, as Python's `X | None`
                parts = [p for p in parts if p != "null"] + ["null"]
            return " | ".join(parts)
        if origin in _SEQ:
            if origin is tuple and (len(args) != 2 or args[1] is not Ellipsis):
                if args == ((),) or not args:
                    return "[]"
                return "[" + ", ".join(self.ts(a, mode, ctx) for a in args) + "]"
            el = self.ts(args[0], mode, ctx) if args else "unknown"
            return f"({el})[]" if " | " in el else f"{el}[]"
        if origin in _MAP:
            k, v = args if args else (str, Any)
            vs = self.ts(v, mode, ctx)
            ks0 = _strip(k)
            if ks0 is str:
                return f"Record<string, {vs}>"
            if get_origin(ks0) is Literal or (inspect.isclass(ks0) and issubclass(ks0, enum.Enum)):
                return f"Partial<Record<{self.ts(k, mode, ctx)}, {vs}>>"
            raise SystemExit(f"unsupported dict key type {k!r}")
        raise SystemExit(f"unsupported annotation {tp0!r}")


