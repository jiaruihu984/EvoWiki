SCHEMA_FILE = "wire-schema.json"
# Annotation keywords dropped from the schema: they take no part in validation and only make the file noisy.
_SCHEMA_NOISE = frozenset({"title", "description", "examples", "default"})


class _OutputSchema(pydantic.json_schema.GenerateJsonSchema):
    """The OUTPUT shape, as FastAPI's response_model and `model_dump(mode="json")` produce it: a defaulted field is
    never left out, so every property is required."""

    def field_is_required(self, field: Any, total: bool) -> bool:
        if field["type"] == "typed-dict-field" and not field.get("required", total):
            return False
        return field.get("serialization_exclude_if") is None


def _tidy(node: Any) -> Any:
    """Strict, ajv-ready JSON Schema: annotation noise dropped; a model object (one with `properties`) closed to
    unknown keys unless it says otherwise (pydantic emits additionalProperties itself for extra="allow"); pydantic's
    OpenAPI-style `discriminator` (its `mapping` is not taken by ajv) dropped: every oneOf member pins its tag with
    `const`, so the oneOf alone tells the members apart."""
    if isinstance(node, list):
        return [_tidy(x) for x in node]
    if not isinstance(node, dict):
        return node
    out = {k: _tidy(v) for k, v in node.items() if k not in _SCHEMA_NOISE and k != "discriminator"}
    if isinstance(node.get("properties"), dict):
        # `properties` maps field names to schemas: a field named like a noise keyword ("title") is a field, not noise
        out["properties"] = {k: _tidy(v) for k, v in node["properties"].items()}
        out.setdefault("additionalProperties", False)
    return out


def wire_schema(g: Gen) -> str:
    """One JSON Schema (draft 2020-12) document whose `$defs` hold the output shape of every model the generated .ts
    files declare one for, keyed by its TS name (RENAMES applied), plus what they reference (enums and the like, under
    pydantic's own names). Deterministic: sorted keys; pydantic's generation is stable for the same models."""
    out_models = [cls for cls in g.order if "out" in g.models[cls].bodies]
    key_map, doc = pydantic.json_schema.models_json_schema(
        [(cls, "serialization") for cls in out_models], by_alias=True, schema_generator=_OutputSchema)
    defs: dict[str, Any] = doc.get("$defs", {})
    rename: dict[str, str] = {}
    for cls in out_models:
        rename[key_map[(cls, "serialization")]["$ref"].removeprefix("#/$defs/")] = g.models[cls].ts
    clash = (set(defs) - set(rename)) & set(rename.values())
    if clash:
        raise SystemExit(f"JSON Schema defs {sorted(clash)}: both a pydantic def name and a TS model name")

    def reref(node: Any) -> Any:
        if isinstance(node, list):
            return [reref(x) for x in node]
        if not isinstance(node, dict):
            return node
        res = {k: reref(v) for k, v in node.items()}
        ref = res.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/$defs/"):
            name = ref.removeprefix("#/$defs/")
            res["$ref"] = "#/$defs/" + rename.get(name, name)
        return res

    schema = {
        "$comment": "GENERATED by scripts/gen_plugin_types.py — do not edit. Output shapes: responses and SSE payloads.",
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "evowiki-wire",
        "$defs": {rename.get(k, k): _tidy(reref(v)) for k, v in defs.items()},
    }
    return json.dumps(schema, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def _trim(body: list[str]) -> list[str]:
    while body and body[0] == "":
        body.pop(0)
    out: list[str] = []
    for ln in body:
        if ln == "" and out and out[-1] == "":
            continue
        out.append(ln)
    return out


def _mark(g: Gen, tp: Any, into: set[type[BaseModel]]) -> None:
    """Every model reachable from `tp` (output side) joins `into`."""
    seen: set[int] = set()

    def walk(t: Any) -> None:
        if id(t) in seen:
            return
        seen.add(id(t))
        t = _strip(t)
        if inspect.isclass(t) and issubclass(t, BaseModel):
            into.add(t)
            for name in t.model_fields:
                walk(_annotation(t, name))
            return
        for a in get_args(t):
            if a is not Ellipsis:
                walk(a)
    walk(tp)


def write(files: dict[str, str]) -> list[Path]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in files.items():
        p = OUT_DIR / name
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8", newline="\n")
            changed.append(p)
    return changed


def stale(files: dict[str, str]) -> list[str]:
    out = []
    for name, text in files.items():
        p = OUT_DIR / name
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            out.append(p.relative_to(ROOT).as_posix())
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is out of date")
    args = ap.parse_args(argv)
    files = generate()
    if args.check:
        bad = stale(files)
        if bad:
            print("stale: " + ", ".join(bad) + " — run python scripts/gen_plugin_types.py")
            return 1
        return 0
    for p in write(files):
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


