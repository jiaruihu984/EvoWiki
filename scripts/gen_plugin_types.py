def _ts_obj(v: Any) -> str:
    """A JSON value as a TS literal (object keys unquoted when they are identifiers)."""
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if re.fullmatch(r"[A-Za-z_$][\w$]*", k) else json.dumps(k, ensure_ascii=False)
            items.append(f"{key}: {_ts_obj(x)}")
        return "{ " + ", ".join(items) + " }"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_ts_obj(x) for x in v) + "]"
    return json.dumps(v, ensure_ascii=False)


def _wrap_items(prefix: str, items: list[str], suffix: str, width: int = 120) -> list[str]:
    """`prefix item, item, ...suffix`, wrapped at `width` with continuation lines indented two more than the prefix."""
    one = prefix + ", ".join(items) + suffix
    if len(one) <= width:
        return [one]
    indent = " " * (len(prefix) - len(prefix.lstrip()) + 2)
    lines, cur = [], prefix
    for i, it in enumerate(items):
        piece = it + ("," if i < len(items) - 1 else "")
        if len(cur) + len(piece) + 1 > width and cur.strip() not in ("", prefix.strip()):
            lines.append(cur.rstrip())
            cur = indent
        cur += piece + " "
    lines.append(cur.rstrip() + suffix)
    return lines


def generate() -> dict[str, str]:
    """file name under OUT_DIR -> file text: `<area>.ts` for each area, plus SCHEMA_FILE."""
    routes = list(_routes())   # imports every route module before the alias scan
    tables = _consts()
    g = Gen()
    table_values: dict[str, tuple[Any, ...]] = {}
    for tbl in tables:
        if isinstance(tbl, Table):
            vals = tuple(tbl.values())
            table_values[tbl.area + ":" + tbl.name] = vals
            g.register_table(tbl, vals)

    for r in routes:
        ctx = r.endpoint.__module__
        if r.body_field is not None:
            g.ts(r.body_field.field_info.annotation, "in", ctx)
        rm = r.response_model
        if rm is not None and rm is not dict:
            _mark(g, rm, g.rest_models)
            g.ts(rm, "out", ctx)
    streams = _streams()
    for name, area, events, tup in streams:
        if tup is not None and tuple(e for e, _ in events) != tuple(tup):
            raise SystemExit(f"{name}: events {[e for e, _ in events]} differ from the Python tuple {list(tup)}")
        for _, m in events:
            _mark(g, m, g.sse_models)
    for root, _ in _sse_roots():
        _mark(g, root, g.sse_models)
    # rendering marks after every mark is known (a model reached from REST and SSE is checked both ways)
    for _, _, events, _ in streams:
        for _, m in events:
            g.ts(m, "out")
    for root, ctx in _sse_roots():
        g.ts(root, "out", ctx)
    g.drain()

    # names: a model whose in / out bodies differ gets NameInput for the input shape
    names: dict[str, str] = {}
    for cls in g.order:
        mo = g.models[cls]
        b = mo.bodies
        names[f"{id(cls)}:out"] = mo.ts
        if "in" in b and "out" in b and b["in"] != b["out"]:
            names[f"{id(cls)}:in"] = mo.ts + "Input"
            g._claim(mo.ts + "Input", f"{_src(cls.__module__)} {cls.__name__} (input)")
        else:
            names[f"{id(cls)}:in"] = mo.ts
    owner: dict[str, set[str]] = {}   # TS name -> the areas that define it
    for cls in g.order:
        mo = g.models[cls]
        for mode in mo.bodies:
            owner.setdefault(names[f"{id(cls)}:{mode}"], set()).add(mo.area)
    for n in g.used_named:
        owner.setdefault(n.ts, set()).add(n.area)
    for name, area, _, _ in streams:
        owner.setdefault(name, set()).add(area)

    ref_re = re.compile("\0(\\d+):(in|out)\0")

    def resolve(text: str, area: str, imports: dict[str, set[str]]) -> str:
        def sub(m: re.Match[str]) -> str:
            nm = names[f"{m.group(1)}:{m.group(2)}"]
            _need(nm, area, imports)
            return nm
        out = ref_re.sub(sub, text)
        code = re.sub(r'"(?:[^"\\]|\\.)*"', '""', out)   # string literals never name a type
        for tok in re.findall(r"\b[A-Z][A-Za-z0-9]*\b", code):
            if tok in owner:
                _need(tok, area, imports)
        return out

    def _need(nm: str, area: str, imports: dict[str, set[str]]) -> None:
        areas = owner[nm]
        if area in areas:
            return
        if len(areas) != 1:
            raise SystemExit(f"{nm} is defined in {sorted(areas)}: ambiguous import into {area}")
        (a,) = areas
        imports.setdefault(a, set()).add(nm)

    files: dict[str, str] = {}
    for area in AREAS:
        imports: dict[str, set[str]] = {}
        body: list[str] = []
        # constant tables and the types they name
        for tbl in tables:
            if tbl.area != area:
                continue
            body += _doc(tbl.doc)
            if isinstance(tbl, Table):
                vals = table_values[area + ":" + tbl.name]
                body += _wrap_items(f"export const {tbl.name} = [", [_ts_obj(v) for v in vals], "] as const;")
                if tbl.type_name:
                    body.append(f"export type {tbl.type_name} = (typeof {tbl.name})[number];")
            else:
                val = tbl.value()
                lit_ = _ts_obj(val)
                body.append(f"export const {tbl.name} = {lit_}{' as const' if isinstance(val, (dict, list)) else ''};")
        for fname, farea, models, doc in _field_tables():
            if farea != area:
                continue
            body += _doc(doc)
            body.append(f"export const {fname} = {{")
            for m in models:
                wire = [(fi.alias or n) for n, fi in m.model_fields.items() if not fi.exclude]
                body += _wrap_items(f"  {m.__name__}: [", [json.dumps(w) for w in wire], "],")
            body.append("} as const;")
        # named aliases without a table
        for n in g.used_named:
            if n.area != area or n.table is not None:
                continue
            body.append("")
            body += _doc((n.doc or "") and n.doc) or [f"/** {n.origin} */"]
            body.append(resolve(f"export type {n.ts} = {n.body};", area, imports))
        # models
        for cls in g.order:
            mo = g.models[cls]
            if mo.area != area:
                continue
            for mode in ("out", "in"):
                if mode not in mo.bodies:
                    continue
                nm = names[f"{id(cls)}:{mode}"]
                if mode == "in" and "out" in mo.bodies and nm == names[f"{id(cls)}:out"]:
                    continue
                body.append("")
                head = f"{_src(cls.__module__)} {cls.__name__}" + (" (request body)" if nm.endswith("Input") else "")
                doc = cls.__doc__ if cls.__doc__ and not cls.__doc__.startswith(
                    ("Usage docs:", "!!! abstract")) else None
                body += _doc(head + (f": {inspect.cleandoc(doc)}" if doc else ""))
                members = [resolve(m, area, imports) for m in mo.bodies[mode]]
                body += [f"export interface {nm} {{", *members, "}"] if members else [f"export type {nm} = Record<string, never>;"]
        # SSE streams
        for name, sarea, events, tup in streams:
            if sarea != area:
                continue
            body.append("")
            body.append("/** SSE frames: the `event:` name and its JSON payload. */")
            parts = []
            for ev, m in events:
                parts.append(f"  | {{ event: {json.dumps(ev)}; data: {resolve(g.ref(m, 'out'), area, imports)} }}")
            body.append(f"export type {name} =")
            body += parts[:-1] + [parts[-1] + ";"]
            if tup is None:
                const = re.sub(r"(?<!^)(?=[A-Z])", "_", name.removesuffix("Event")).upper() + "_EVENTS"
                body += _wrap_items(f"export const {const} = [", [json.dumps(e) for e, _ in events], "] as const;")
                body.append(f"/** The pydantic model of each {const} payload. */")
                body += _wrap_items(f"export const {const[:-1]}_MODELS = {{ ", [f"{e}: {json.dumps(m.__name__)}" for e, m in events],
                                    " } as const;")
        lines = [HEADER.rstrip("\n"), f"/** Wire types of {AREA_DOC[area]} */"]
        for a in AREAS:
            if a in imports and a != area:
                lines += _wrap_items("import type { ", sorted(imports[a]), f" }} from \"./{a}\";")
        files[f"{area}.ts"] = "\n".join(lines + [""] + _trim(body)) + "\n"
    files[SCHEMA_FILE] = wire_schema(g)
    return files


