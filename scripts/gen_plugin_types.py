@dataclass(frozen=True)
class Table:
    """`export const NAME = [...] as const;` and, when `type_name` is set, `export type T = (typeof NAME)[number];`
    (every union with exactly these members renders as T)."""
    name: str
    area: str
    values: typing.Callable[[], tuple[Any, ...]]
    type_name: str | None = None
    doc: str = ""


@dataclass(frozen=True)
class Value:
    """`export const NAME = <json>;` (objects and arrays `as const`)."""
    name: str
    area: str
    value: typing.Callable[[], Any]
    doc: str = ""


def lit(tp: Any) -> tuple[Any, ...]:
    """The members of a Literal (through Optional / Annotated) or a StrEnum, in declaration order."""
    tp = _strip(tp)
    if inspect.isclass(tp) and issubclass(tp, enum.Enum):
        return tuple(m.value for m in tp)
    if get_origin(tp) in (Union, types.UnionType):
        parts = [a for a in get_args(tp) if a is not type(None)]
        if len(parts) != 1:
            raise TypeError(f"not a single Literal: {tp!r}")
        return lit(parts[0])
    if get_origin(tp) is Literal:
        return get_args(tp)
    raise TypeError(f"not a Literal: {tp!r}")


def ftype(model: type[BaseModel], name: str) -> Any:
    return model.model_fields[name].annotation


def constraint(model: type[BaseModel], name: str, key: str) -> Any:
    for m in model.model_fields[name].metadata:
        if getattr(m, key, None) is not None:
            return getattr(m, key)
    raise KeyError(f"{model.__name__}.{name} has no {key}")


def union_tags(union: Any, tag: str) -> tuple[str, ...]:
    out = []
    for m in get_args(_strip(union)):
        (v,) = lit(ftype(m, tag))
        out.append(v)
    return tuple(out)


