"""Generate the Obsidian plugin's wire types from the backend's pydantic models.

    python scripts/gen_plugin_types.py           # writes obsidian-plugin/src/generated/*.ts and wire-schema.json
    python scripts/gen_plugin_types.py --check   # exits 1 when a committed file is stale

Which models: every request body and response model of the FastAPI app's routes (`create_app`), minus
the routes the plugin never calls (EXCLUDED_PATHS), plus what OpenAPI cannot see: the SSE payloads
(`_streams`, `_sse_roots`). Everything they reference is followed. Constant tables (`_consts`, `_field_tables`) are read from the Python values, so a backend
change shows up as a diff in the generated file (tests/service/test_plugin_types_fresh.py fails until
it is regenerated).

Shapes:
- Responses (and SSE payloads) are the OUTPUT shape: every field is present (FastAPI and model_dump
  never leave a defaulted field out), `exclude=True` fields are dropped. REST responses use field
  aliases (FastAPI's response_model_by_alias); an SSE payload is `model_dump(mode="json")`, which uses
  them only when the model sets `serialize_by_alias` (a mismatch fails the generator).
- Request bodies are the INPUT shape: a field with a default is optional (`name?:`), aliases are the
  validation aliases.
- A model used both ways whose shapes differ gets two interfaces: `Name` (output) and `NameInput`.
- Named Literal aliases, StrEnums and discriminated-union aliases keep their Python name (RENAMES
  maps the few that collide or that the plugin names differently); an inline Literal is a union.
- Unknown annotations raise (fail closed): nothing becomes `any` by accident.

Output: one file per area (wiki / sources / bot / assistant / service), assigned by Python module.
The output is deterministic (route order, declaration order, sorted imports)."""

