def area_of(module: str) -> str:
    if module.startswith(("evowiki.assistant", "evowiki.agent")) or module == "evowiki.service.routes_assistant":
        return "assistant"
    if module.startswith("evowiki.bot"):
        return "bot"
    if module == "evowiki.service.source_schemas" or module.startswith("evowiki.sources"):
        return "sources"
    if module in ("evowiki.service.routes_users", "evowiki.service.routes_usage", "evowiki.content.models") \
            or module.startswith("evowiki.llm"):
        return "service"
    return "wiki"


