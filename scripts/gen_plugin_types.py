def _routes():
    from fastapi.routing import APIRoute

    from evowiki.service.app import create_app

    def walk(routes):
        for r in routes:
            if isinstance(r, APIRoute):
                yield r
            elif hasattr(r, "original_router"):
                yield from walk(r.original_router.routes)
            elif getattr(r, "routes", None) is not None and not isinstance(r, APIRoute):
                yield from walk(r.routes)

    app = create_app(None)  # type: ignore[arg-type]  # only the routes are read; no service is touched
    for r in walk(app.routes):
        if r.path.startswith(EXCLUDED_PATHS):
            continue
        if any((m, r.path) in EXCLUDED_ROUTES for m in r.methods):
            continue
        yield r


